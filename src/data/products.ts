export const allProducts: Product[] = productCategories.flatMap(cat => cat.products);
export const featuredProducts = allProducts.filter(p => p.featured);

export function getProductBySlug(slug: string): Product | undefined {
  return allProducts.find(p => p.slug === slug);
}

export function getProductCategory(slug: string): ProductCategory | undefined {
  return productCategories.find(c => c.slug === slug);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return allProducts.filter(p => p.categorySlug === categorySlug);
}

export function getRelatedProducts(product: Product): Product[] {
  return product.relatedProducts
    .map(slug => getProductBySlug(slug))
    .filter((p): p is Product => p !== undefined)
    .slice(0, 4);
}

